import {chromium} from 'playwright-core';
import assert from 'node:assert/strict';
const [base] = process.argv.slice(2);
let browser;
let phase = 'launch';
try {
  browser = await chromium.launch({headless: true, args: ['--no-sandbox'], timeout: 10000});
  const page = await browser.newPage({viewport: {width: 390, height: 844}});
  phase = 'authentication';
  await page.goto(base + '/sign-in');
  await page.getByLabel('Correo electrónico', {exact: true}).fill(process.env.ADMIN_EMAIL);
  await page.getByLabel('Contraseña', {exact: true}).fill('correct-password-123');
  await page.getByRole('button', {name: 'Iniciar sesión', exact: true}).click();
  await page.waitForSelector('.phx-connected #workspace');
  await page.getByRole('link', {name: 'Administración', exact: true}).click();
  await page.waitForSelector('.phx-connected #administration');
  phase = 'explicit-provisioning';
  assert.equal(await page.locator('#no-active-configuration').count(), 1);
  await page.locator('#provision-presets').click();
  await page.waitForSelector('#strategy-position_aware article');
  const balanced = await page.locator('#strategy-balanced article').getAttribute('id');
  const positional = await page.locator('#strategy-position_aware article').getAttribute('id');
  assert.equal(await page.locator('.active-configuration').count(), 0);
  await page.locator('#provision-presets').click();
  await page.waitForSelector('#activation-notice');
  assert.equal(await page.locator('#strategy-balanced article').count(), 1);
  assert.equal(await page.locator('#strategy-position_aware article').count(), 1);
  phase = 'immutable-editor';
  await page.locator(`#${balanced} button[phx-click="edit"]`).click();
  await page.waitForSelector('#configuration-form');
  assert.equal(await page.getByLabel('General: Goles', {exact: true}).inputValue(), '4');
  await page.getByLabel('General: Goles', {exact: true}).fill('6.25');
  await page.getByLabel('Referencia: Goles', {exact: true}).fill('3');
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', {name: 'Guardar nueva versión', exact: true}).click();
  await page.waitForSelector('#configuration-form', {state: 'detached'});
  assert.equal(await page.locator('#strategy-balanced article').count(), 2);
  assert.equal(await page.locator('.active-configuration').count(), 0);
  const custom = await page.locator(`#strategy-balanced article:not(#${balanced})`).getAttribute('id');
  await page.locator(`#${custom} button[phx-click="edit"]`).click();
  await page.waitForSelector('#configuration-form');
  assert.equal(await page.getByLabel('General: Goles', {exact: true}).inputValue(), '6.25');
  assert.equal(await page.getByLabel('Referencia: Goles', {exact: true}).inputValue(), '3');
  await page.getByRole('button', {name: 'Cancelar', exact: true}).click();
  await page.locator(`#${balanced} button[phx-click="edit"]`).click();
  await page.waitForSelector('#configuration-form');
  assert.equal(await page.getByLabel('General: Goles', {exact: true}).inputValue(), '4');
  await page.getByRole('button', {name: 'Cancelar', exact: true}).click();
  phase = 'independent-activation';
  await page.locator(`#${custom} button[phx-click="activate"]`).click();
  await page.waitForSelector(`#${custom} .active-configuration`);
  await page.locator(`#${positional} button[phx-click="activate"]`).click();
  await page.waitForSelector(`#${positional} .active-configuration`);
  await page.reload();
  await page.waitForSelector(`#${positional} .active-configuration`);
  assert.match(await page.locator(`#${positional}`).innerText(), /Predefinida educativa v1/);
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  process.stdout.write('ADMINISTRATION_BROWSER status=complete\n');
} catch {
  process.stderr.write(`ADMINISTRATION_BROWSER status=failed category=${phase}\n`);
  process.exitCode = 1;
} finally {
  await browser?.close();
}
