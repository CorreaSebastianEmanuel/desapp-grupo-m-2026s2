import {chromium, request} from 'playwright-core';
import assert from 'node:assert/strict';
const [base, mode = 'browser'] = process.argv.slice(2);
const email = process.env.WORKSPACE_EMAIL;
const second = process.env.WORKSPACE_SECOND_EMAIL;
const password = process.env.WORKSPACE_PASSWORD;
const control = process.env.WORKSPACE_CONTROL;
let browser;
let phase = 'prerequisites';
const change = async query => {
  const response = await fetch(`${base}/__test/control?${query}`, {headers: {'x-test-control': control}});
  assert.equal(response.status, 200);
};
const csrf = html => html.match(/name="_csrf_token"[^>]*value="([^"]+)"/)?.[1];
const waitUntil = async (fn, timeout = 2000) => {
  const started = Date.now();
  while (!(await fn())) {
    assert(Date.now() - started < timeout, 'deadline exceeded');
    await new Promise(resolve => setTimeout(resolve, 20));
  }
};
try {
  assert(base && email && second && password && control);
  const ready = await fetch(`${base}/sign-in`);
  assert.equal(ready.status, 200);
  assert((await ready.text()).includes('Sign in'));
  if (mode === 'http') {
    phase = 'http-contract';
    const ctx = await request.newContext({baseURL: base, extraHTTPHeaders: {connection: 'close'}});
    const form = await ctx.get('/sign-in');
    assert.equal(form.status(), 200);
    assert.equal(form.headers()['cache-control'], 'no-store');
    const cookie = form.headers()['set-cookie'];
    assert(cookie.includes('HttpOnly') && cookie.includes('SameSite=Lax'));
    const token = csrf(await form.text());
    assert(token);
    const forged = await ctx.post('/sign-in', {form: {email, password}, maxRedirects: 0});
    assert.equal(forged.status(), 403);
    // A CSRF exception closes the HTTP/1 connection; each request uses a fresh
    // connection so the full adversarial sequence tests the app, not a stale pool.
    phase = 'cross-origin';
    const cross = await ctx.post('/sign-in', {headers: {origin: 'https://hostile.invalid'}, form: {_csrf_token: token, email, password}, maxRedirects: 0});
    assert.equal(cross.status(), 403);
    phase = 'invalid-credentials';
    const bad = await ctx.post('/sign-in', {form: {_csrf_token: token, email, password: 'wrong'}, maxRedirects: 0});
    assert.equal(bad.status(), 422);
    assert((await bad.text()).includes('Unable to sign in'));
    await change('failure=all');
    const unavailable = await ctx.post('/sign-in', {form: {_csrf_token: token, email, password}, maxRedirects: 0});
    assert.equal(unavailable.status(), 503);
    assert((await unavailable.text()).includes('retry'));
    await change('failure=clear');
    phase = 'http-login';
    const login = await ctx.post('/sign-in', {form: {_csrf_token: token, email, password, return_to: '/conditional-orders'}, maxRedirects: 0});
    assert.equal(login.status(), 303);
    assert.equal(login.headers().location, '/conditional-orders');
    for (const [path, heading] of [['/portfolio','Portfolio'],['/conditional-orders','Conditional orders']]) {
      const page = await ctx.get(path);
      assert.equal(page.status(), 200);
      assert.equal(page.headers()['cache-control'], 'no-store');
      assert((await page.text()).includes(heading));
    }
    assert.equal((await ctx.get('/api/players')).status(), 401);
    assert.equal((await ctx.get('/')).status(), 200);
    assert.equal((await ctx.get('/docs')).status(), 200);
    assert.equal((await ctx.get('/sign-out')).status(), 404);
    const missing = await ctx.get('/unknown-workspace');
    assert.equal(missing.status(), 404);
    assert((await missing.text()).includes('Sign in'));
    phase = 'owned-resource-denial';
    const denied = await ctx.get('/__test/owned-resource', {headers: {'x-test-control': control}});
    assert.equal(denied.status(), 403);
    const denial = await denied.text();
    assert(denial.includes('Access denied') && denial.includes('/portfolio'));
    assert(!denial.includes(second) && !denial.includes('other-user-private'));
    assert.equal((await ctx.get('/portfolio')).status(), 200);
    phase = 'forged-websocket';
    const forgedSocket = await ctx.get('/live/websocket?vsn=2.0.0&_csrf_token=forged', {
      headers: {origin: 'https://hostile.invalid', connection: 'Upgrade', upgrade: 'websocket', 'sec-websocket-version': '13', 'sec-websocket-key': 'dGhlIHNhbXBsZSBub25jZQ=='},
      maxRedirects: 0
    });
    assert.equal(forgedSocket.status(), 403);
    assert(!(await forgedSocket.text()).includes(email));
    phase = 'http-logout';
    const privatePage = await ctx.get('/portfolio');
    const logoutToken = csrf(await privatePage.text());
    await change('failure=revoke');
    const failedOut = await ctx.post('/sign-out', {form: {_csrf_token: logoutToken}, maxRedirects: 0});
    assert.equal(failedOut.status(), 503);
    assert((await failedOut.text()).includes('Retry sign out'));
    await change('failure=clear');
    const out = await ctx.post('/sign-out', {form: {_csrf_token: logoutToken}, maxRedirects: 0});
    assert.equal(out.status(), 303);
    assert.equal((await ctx.get('/portfolio', {maxRedirects: 0})).status(), 303);
    await ctx.dispose();
  } else {
    browser = await chromium.launch({headless: true, args: ['--no-sandbox']});
    const ctx = await browser.newContext({viewport: {width: 1280, height: 800}});
    const page = await ctx.newPage();
    let replayed = 0;
    page.on('websocket', ws => ws.on('framesent', frame => { if (String(frame.payload).includes('must_not_replay')) replayed++; }));
    const signIn = async (p, who = email, target = '') => {
      await p.goto(`${base}/sign-in${target}`);
      await p.getByLabel('Email', {exact:true}).fill(who);
      await p.getByLabel('Password', {exact:true}).fill(password);
      await p.getByRole('button', {name:'Sign in', exact:true}).click();
      await p.waitForSelector('#workspace.phx-connected, .phx-connected #workspace');
    };
    phase = 'credentials-and-keyboard';
    await page.goto(`${base}/sign-in`);
    await page.getByLabel('Email', {exact:true}).focus();
    await page.keyboard.type(email);
    await page.keyboard.press('Tab');
    await page.keyboard.type('wrong');
    await page.keyboard.press('Tab');
    await page.keyboard.press('Enter');
    await page.getByRole('alert').waitFor();
    assert.equal(await page.getByLabel('Password', {exact:true}).inputValue(), '');
    assert.equal(await page.getByLabel('Password', {exact:true}).getAttribute('aria-describedby'), 'sign-in-message');
    await page.getByLabel('Password', {exact:true}).fill(password);
    await page.getByRole('button', {name: 'Sign in', exact:true}).focus();
    await page.keyboard.press('Enter');
    await page.waitForSelector('.phx-connected #workspace');
    assert((await page.locator('body').innerText()).includes(email));
    assert.equal(await page.locator('[aria-current=page]').count(), 1);
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    phase = 'stale-authenticated-submission';
    const stale = await page.evaluate(async ([second, password]) => {
      const token = document.querySelector('form[action="/sign-out"] input[name="_csrf_token"]').value;
      const response = await fetch('/sign-in', {method:'POST', body:new URLSearchParams({_csrf_token:token,email:second,password})});
      return {status: response.status, path: new URL(response.url).pathname, body: await response.text()};
    }, [second, password]);
    assert.equal(stale.status, 200);
    assert.equal(stale.path, '/portfolio');
    assert(stale.body.includes(email) && !stale.body.includes(second));
    phase = 'navigation-and-isolation';
    await page.getByRole('link', {name: 'Conditional orders', exact:true}).focus();
    const focus = await page.evaluate(() => getComputedStyle(document.activeElement).outlineStyle);
    assert.notEqual(focus, 'none');
    await page.keyboard.press('Enter');
    await page.getByRole('heading', {name: 'Conditional orders', exact:true}).waitFor();
    await page.getByRole('link', {name: 'Portfolio', exact:true}).click();
    await page.getByRole('heading', {name: 'Portfolio', exact:true}).waitFor();
    const tab = await ctx.newPage();
    await tab.goto(`${base}/conditional-orders`);
    await tab.waitForSelector('.phx-connected #workspace');
    phase = 'two-tab-signout';
    const started = Date.now();
    await page.getByRole('button', {name: 'Sign out', exact:true}).focus();
    await page.keyboard.press('Enter');
    await waitUntil(async () => !(await tab.locator('body').innerText()).includes(email));
    assert(Date.now() - started <= 2000);
    await tab.waitForURL('**/sign-in?notice=ended');
    phase = 'account-switch-history';
    await signIn(page, second);
    await page.goBack();
    await page.waitForTimeout(300);
    assert(!(await page.locator('body').innerText()).includes(email));
    await page.goto(`${base}/portfolio`);
    assert((await page.locator('body').innerText()).includes(second));
    phase = 'two-tab-expiry';
    await tab.goto(`${base}/conditional-orders`);
    await tab.waitForSelector('.phx-connected #workspace');
    await page.waitForSelector('.phx-connected #workspace');
    const expiryStarted = Date.now();
    await change('advance=900000000');
    await waitUntil(async () => !(await page.locator('body').innerText()).includes(second) && !(await tab.locator('body').innerText()).includes(second));
    assert(Date.now() - expiryStarted <= 2000);
    phase = 'valid-reconnect-refresh';
    await signIn(page);
    await ctx.setOffline(true);
    await waitUntil(async () => !(await page.locator('body').innerText()).includes(email));
    const queued = await page.evaluate(() => {
      const channel = window.liveSocket?.main?.channel;
      if (!channel) return false;
      channel.push('event', {type:'click', event:'must_not_replay', value:{}});
      return true;
    });
    assert(queued);
    await change(`rename=${encodeURIComponent(email)}&to=changed%40example.com`);
    await ctx.setOffline(false);
    await waitUntil(async () => (await page.locator('body').innerText()).includes('changed@example.com'), 5000);
    assert.equal(replayed, 0);
    await change(`rename=changed%40example.com&to=${encodeURIComponent(email)}`);
    await page.reload();
    await page.waitForSelector('.phx-connected #workspace');
    phase = 'offline-reconnect';
    await ctx.setOffline(true);
    await waitUntil(async () => !(await page.locator('body').innerText()).includes(email));
    assert(await page.getByRole('alert').isVisible());
    await change('advance=900000000');
    await ctx.setOffline(false);
    phase = 'offline-expired-notice';
    await page.waitForURL(/\/sign-in\?.*notice=ended/);
    assert(!(await page.locator('body').innerText()).includes(email));
    phase = 'safe-returns';
    await signIn(page, email, '?return_to=%2Fconditional-orders');
    await page.getByRole('heading', {name: 'Conditional orders', exact:true}).waitFor();
    await page.getByRole('button', {name:'Sign out', exact:true}).click();
    await signIn(page, email, '?return_to=https%3A%2F%2Fevil.invalid');
    await page.getByRole('heading', {name: 'Portfolio', exact:true}).waitFor();
    phase = 'secret-transport';
    const cookies = await ctx.cookies();
    assert(cookies.some(c => c.name === '_football_market_key' && c.httpOnly && c.sameSite === 'Lax'));
    assert.equal(await page.evaluate(() => document.cookie), '');
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0);
    assert(!(await page.content()).includes(password));
    phase = 'expired-transport-recovery';
    await ctx.setOffline(true);
    await waitUntil(async () => !(await page.locator('body').innerText()).includes(email));
    await change('advance=900000000');
    await ctx.clearCookies({name: '_football_market_key'});
    assert(!(await ctx.cookies()).some(c => c.name === '_football_market_key'));
    await ctx.setOffline(false);
    await page.goto(`${base}/portfolio`);
    await page.waitForURL(/\/sign-in\?.*notice=ended/);
    assert((await page.getByRole('alert').innerText()).includes('Your session ended'));
    assert(!(await page.locator('body').innerText()).includes(email));
    await signIn(page);
    phase = 'unavailable-recovery';
    await page.getByRole('button', {name:'Sign out', exact:true}).click();
    await change('failure=all');
    await page.reload();
    assert((await page.locator('body').innerText()).includes('temporarily unavailable'));
    await change('failure=clear');
    await page.getByRole('link', {name:'Retry sign in'}).click();
    await page.getByLabel('Email', {exact:true}).waitFor();
    await ctx.close();
  }
  process.stdout.write(`WORKSPACE_RECEIPT mode=${mode} status=complete\n`);
} catch (_) {
  process.stderr.write(`WORKSPACE_OUTCOME mode=${mode} status=failed category=${phase}\n`);
  process.exitCode = 1;
} finally {
  await change('failure=clear').catch(() => {});
  await browser?.close();
}
